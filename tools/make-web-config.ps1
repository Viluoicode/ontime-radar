# Sinh web/js/config.js từ Outputs của stack (API URL, Cognito) – không chép tay.
#   .\tools\make-web-config.ps1                                   # chạy thử ở máy: http://localhost:5500/
#   .\tools\make-web-config.ps1 -RedirectUri https://dxxxx.cloudfront.net/
# Các giá trị này không bí mật (client id của app công khai), nhưng file vẫn không commit
# vì mỗi môi trường deploy có giá trị khác nhau.
param(
    [string]$StackName = "shipment-sla",
    [string]$Region = "ap-southeast-1",
    [string]$RedirectUri = "http://localhost:5500/",
    [string]$OutFile = (Join-Path $PSScriptRoot "..\web\js\config.js")
)
$ErrorActionPreference = "Stop"

$outputs = aws cloudformation describe-stacks --stack-name $StackName --region $Region --query "Stacks[0].Outputs" --output json | ConvertFrom-Json
$o = @{}; $outputs | ForEach-Object { $o[$_.OutputKey] = $_.OutputValue }
$authDomain = ([Uri]$o.LoginUrl).GetLeftPart([UriPartial]::Authority)

$js = @"
// GENERATED by tools/make-web-config.ps1 – do not edit, do not commit.
export const CONFIG = Object.freeze({
  apiUrl: "$($o.ApiUrl)",
  authDomain: "$authDomain",
  clientId: "$($o.UserPoolClientId)",
  redirectUri: "$RedirectUri",
  region: "$Region"
});
"@
$path = [IO.Path]::GetFullPath($OutFile)
[IO.File]::WriteAllText($path, $js, (New-Object Text.UTF8Encoding $false))
Write-Host "Đã ghi $path (redirect: $RedirectUri)" -ForegroundColor Green
